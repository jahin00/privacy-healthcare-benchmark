class RDPAccountant:
    def __init__(self, target_epsilon, delta, orders, releases_per_round, sensitivity):
        self.target = float(target_epsilon)
        self.delta = float(delta)
        self.orders = [float(x) for x in orders]
        self.releases_per_round = int(releases_per_round)
        self.sensitivity = float(sensitivity)
        self.steps = 0

    def epsilon(self, sigma):
        if sigma <= 0:
            return float("inf"), None
        best = float("inf")
        best_order = None
        for alpha in self.orders:
            rdp = self.steps * self.releases_per_round * alpha * (self.sensitivity ** 2) / (2.0 * (sigma * self.sensitivity) ** 2)
            eps = rdp + math.log(1.0 / self.delta) / (alpha - 1.0)
            if eps < best:
                best = eps
                best_order = alpha
        return float(best), best_order

    def solve_sigma(self):
        lo = 1e-4
        hi = 1e3
        self.steps = CONFIG["num_rounds"]
        for _ in range(100):
            mid = (lo + hi) / 2.0
            eps, _ = self.epsilon(mid)
            if eps > self.target:
                lo = mid
            else:
                hi = mid
        self.steps = 0
        return hi

    def step(self):
        self.steps += 1

class SecureAggregator:
    """Research simulation: additive random shares are formed and summed locally."""
    def __init__(self, num_clients):
        self.num_clients = int(num_clients)

    def aggregate(self, vectors, weights):
        if not vectors:
            return np.array([])
        total = np.zeros_like(vectors[0], dtype=float)
        for w, vec in zip(weights, vectors):
            weighted = w * vec
            if self.num_clients <= 1:
                total += weighted
                continue
            shares = []
            random_shares = [np.random.normal(0.0, 1.0, weighted.shape) for _ in range(self.num_clients - 1)]
            shares.extend(random_shares)
            final_share = weighted - sum(random_shares)
            shares.append(final_share)
            total += sum(shares)
        return finite_array(total)

def clip_vec(v, C):
    v = finite_array(v)
    n = float(np.linalg.norm(v))
    if n > C:
        v *= (C / (n + 1e-12))
    return finite_array(v)

