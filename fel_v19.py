class FedLinear:
    def __init__(self, d, lr):
        self.w = np.zeros(d, dtype=float)
        self.b = 0.0
        self.lr = float(lr)

        # SCAFFOLD state.
        self.c = np.zeros_like(self.w)
        self.c_b = 0.0
        self.ci = np.zeros_like(self.w)
        self.ci_b = 0.0
    def state(self, include_client=True):
        out = {
            "w": self.w.copy(),
            "b": float(self.b),
            "c": self.c.copy(),
            "c_b": float(self.c_b),
        }
        if include_client:
            out.update({
                "ci": self.ci.copy(),
                "ci_b": float(self.ci_b),
            })
        return out
    def set_global(self, state):
        self.w = finite_array(state["w"]).reshape(self.w.shape)
        self.b = float(np.asarray(state["b"]).reshape(-1)[0])
        self.c = finite_array(state.get("c", np.zeros_like(self.w))).reshape(self.w.shape)
        self.c_b = float(np.asarray(state.get("c_b", 0.0)).reshape(-1)[0])
        self.w = np.clip(self.w, -CONFIG["parameter_clip"], CONFIG["parameter_clip"])
        self.b = float(np.clip(self.b, -CONFIG["parameter_clip"], CONFIG["parameter_clip"]))
    def predict_p(self, X):
        return sigmoid(finite_array(X) @ self.w + self.b).reshape(-1)
    def local_update(self, X, y, global_state, method, epochs, mu, cw):
        method = method.lower()
        ci_old = self.ci.copy()
        ci_b_old = self.ci_b
        self.set_global(global_state)
        self.ci = ci_old
        self.ci_b = ci_b_old
        w0 = self.w.copy()
        b0 = self.b
        sw = np.where(y == 1, cw[1], cw[0])
        sw = sw / (sw.mean() + 1e-12)

        for _ in range(int(epochs)):
            p = self.predict_p(X)
            err = (p - y) * sw
            gw = X.T @ err / max(len(y), 1)
            gb = float(err.mean())
            if method == "fedprox":
                gw += mu * (self.w - w0)
                gb += mu * (self.b - b0)
            elif method == "scaffold":
                gw += -self.ci + self.c
                gb += -self.ci_b + self.c_b
            gw = np.clip(finite_array(gw), -CONFIG["gradient_clip"], CONFIG["gradient_clip"])
            gb = float(np.clip(gb, -CONFIG["gradient_clip"], CONFIG["gradient_clip"]))
            self.w = np.clip(self.w - self.lr * gw, -CONFIG["parameter_clip"], CONFIG["parameter_clip"])
            self.b = float(np.clip(self.b - self.lr * gb, -CONFIG["parameter_clip"], CONFIG["parameter_clip"]))

        ci_delta = np.zeros_like(self.ci)
        ci_b_delta = 0.0
        if method == "scaffold":
            k = max(int(epochs), 1)
            self.ci = self.ci - self.c + (w0 - self.w) / (k * self.lr + 1e-12)
            self.ci_b = self.ci_b - self.c_b + (b0 - self.b) / (k * self.lr + 1e-12)
            self.ci = finite_array(self.ci)
            self.ci_b = float(np.nan_to_num(self.ci_b))
            ci_delta = finite_array(self.ci - ci_old)
            ci_b_delta = float(self.ci_b - ci_b_old)

        out = self.state(include_client=True)
        out["ci_delta"] = ci_delta
        out["ci_b_delta"] = ci_b_delta
        return out

class FedDNN:

    def __init__(self, d_in, h1, h2, lr):
        rng = np.random.RandomState(SEED + d_in)
        self.W1 = rng.normal(0.0, np.sqrt(2.0 / d_in), (d_in, h1))
        self.b1 = np.zeros(h1)
        self.W2 = rng.normal(0.0, np.sqrt(2.0 / h1), (h1, h2))
        self.b2 = np.zeros(h2)
        self.W3 = rng.normal(0.0, np.sqrt(2.0 / h2), (h2, 1))
        self.b3 = np.zeros(1)
        self.lr = float(lr)
        for p in ["W1", "b1", "W2", "b2", "W3", "b3"]:
            setattr(self, "c" + p, np.zeros_like(getattr(self, p)))
            setattr(self, "ci" + p, np.zeros_like(getattr(self, p)))

    def state(self, include_client=True):
        names = [
            "W1", "b1", "W2", "b2", "W3", "b3",
            "cW1", "cb1", "cW2", "cb2", "cW3", "cb3",
        ]
        if include_client:
            names += ["ciW1", "cib1", "ciW2", "cib2", "ciW3", "cib3"]
        return {k: finite_array(getattr(self, k)).copy() for k in names}

    def set_global(self, state):
        names = [
            "W1", "b1", "W2", "b2", "W3", "b3",
            "cW1", "cb1", "cW2", "cb2", "cW3", "cb3",
        ]
        for k in names:
            target = getattr(self, k)
            value = state.get(k, np.zeros_like(target))
            setattr(self, k, finite_array(value).reshape(target.shape).copy())
        for k in ["W1", "b1", "W2", "b2", "W3", "b3"]:
            setattr(self, k, np.clip(finite_array(getattr(self, k)), -CONFIG["parameter_clip"], CONFIG["parameter_clip"]))

    def predict_p(self, X):
        X = finite_array(X)
        h1 = np.tanh(X @ self.W1 + self.b1)
        h2 = np.tanh(h1 @ self.W2 + self.b2)
        return sigmoid((h2 @ self.W3 + self.b3).ravel())

    def local_update(self, X, y, global_state, method, epochs, mu, cw):
        method = method.lower()
        client_ci_old = {k: getattr(self, k).copy() for k in ["ciW1", "cib1", "ciW2", "cib2", "ciW3", "cib3"]}
        self.set_global(global_state)
        for k, v in client_ci_old.items():
            setattr(self, k, v.copy())
        w0 = {k: getattr(self, k).copy() for k in ["W1", "b1", "W2", "b2", "W3", "b3"]}
        m = {k: np.zeros_like(v) for k, v in w0.items()}
        v = {k: np.zeros_like(v) for k, v in w0.items()}
        t = 0
        n = len(y)
        batch_size = max(16, min(CONFIG["dnn_batch_size"], n))
        rng = np.random.RandomState(SEED + (n % 1000003))
        X = finite_array(X)
        y = np.asarray(y, dtype=float)

        for _ in range(int(epochs)):
            order = rng.permutation(n)
            for start in range(0, n, batch_size):
                idx = order[start:start + batch_size]
                Xb = X[idx]
                yb = y[idx]
                sw = np.where(yb == 1, cw[1], cw[0])
                sw = (sw / (sw.mean() + 1e-12)).reshape(-1, 1)
                h1 = np.tanh(Xb @ self.W1 + self.b1)
                h2 = np.tanh(h1 @ self.W2 + self.b2)
                z = h2 @ self.W3 + self.b3
                p = sigmoid(z)
                err = (p - yb.reshape(-1, 1)) * sw
                nb = max(len(yb), 1)
                gW3 = h2.T @ err / nb + CONFIG["dnn_l2"] * self.W3
                gb3 = err.mean(axis=0)
                dh2 = (err @ self.W3.T) * (1.0 - h2 * h2)
                gW2 = h1.T @ dh2 / nb + CONFIG["dnn_l2"] * self.W2
                gb2 = dh2.mean(axis=0)
                dh1 = (dh2 @ self.W2.T) * (1.0 - h1 * h1)
                gW1 = Xb.T @ dh1 / nb + CONFIG["dnn_l2"] * self.W1
                gb1 = dh1.mean(axis=0)
                grads = {"W1": gW1, "b1": gb1, "W2": gW2, "b2": gb2, "W3": gW3, "b3": gb3}
                if method == "fedprox":
                    for k in grads:
                        grads[k] += mu * (getattr(self, k) - w0[k])
                elif method == "scaffold":
                    for k in grads:
                        grads[k] += -getattr(self, "ci" + k) + getattr(self, "c" + k)
                for k in grads:
                    grads[k] = np.clip(finite_array(grads[k]), -CONFIG["gradient_clip"], CONFIG["gradient_clip"])
                t += 1
                for k, g in grads.items():
                    m[k] = CONFIG["adam_beta1"] * m[k] + (1.0 - CONFIG["adam_beta1"]) * g
                    v[k] = CONFIG["adam_beta2"] * v[k] + (1.0 - CONFIG["adam_beta2"]) * (g * g)
                    mh = m[k] / (1.0 - CONFIG["adam_beta1"] ** t)
                    vh = v[k] / (1.0 - CONFIG["adam_beta2"] ** t)
                    value = getattr(self, k) - self.lr * mh / (np.sqrt(vh) + CONFIG["adam_eps"])
                    setattr(self, k, np.clip(finite_array(value), -CONFIG["parameter_clip"], CONFIG["parameter_clip"]))

        ci_delta = {k: np.zeros_like(getattr(self, k)) for k in ["ciW1", "cib1", "ciW2", "cib2", "ciW3", "cib3"]}
        if method == "scaffold":
            k_steps = max(t, 1)
            for p in ["W1", "b1", "W2", "b2", "W3", "b3"]:
                ci_name = "ci" + p
                c_name = "c" + p
                updated = (getattr(self, ci_name) - getattr(self, c_name) +
                           (w0[p] - getattr(self, p)) / (k_steps * self.lr + 1e-12))
                setattr(self, ci_name, finite_array(updated))
                ci_delta[ci_name] = finite_array(getattr(self, ci_name) - client_ci_old[ci_name])

        out = self.state(include_client=True)
        out["ci_delta"] = ci_delta
        out["n_steps"] = t
        return out

class FedMeta:

    def __init__(self, lr):
        self.w = np.zeros(2, dtype=float)
        self.b = 0.0
        self.lr = float(lr)
        self.c = np.zeros(2)
        self.c_b = 0.0
        self.ci = np.zeros(2)
        self.ci_b = 0.0

    def state(self, include_client=True):
        out = {
            "w": self.w.copy(),
            "b": float(self.b),
            "c": self.c.copy(),
            "c_b": float(self.c_b),
        }
        if include_client:
            out.update({
                "ci": self.ci.copy(),
                "ci_b": float(self.ci_b),
            })
        return out

    def set_global(self, state):
        self.w = np.clip(finite_array(state["w"]).reshape(2), -CONFIG["parameter_clip"], CONFIG["parameter_clip"])
        self.b = float(np.clip(np.asarray(state["b"]).reshape(-1)[0], -CONFIG["parameter_clip"], CONFIG["parameter_clip"]))
        self.c = finite_array(state.get("c", np.zeros(2))).reshape(2)
        self.c_b = float(np.asarray(state.get("c_b", 0.0)).reshape(-1)[0])

    def predict_p(self, P):
        return sigmoid(finite_array(P) @ self.w + self.b).reshape(-1)

    def local_update(self, P, y, global_state, method, epochs, mu, cw):
        method = method.lower()
        ci_old = self.ci.copy()
        ci_b_old = self.ci_b
        self.set_global(global_state)
        self.ci = ci_old
        self.ci_b = ci_b_old
        w0 = self.w.copy()
        b0 = self.b
        sw = np.where(y == 1, cw[1], cw[0])
        sw = sw / (sw.mean() + 1e-12)

        for _ in range(int(epochs)):
            p = self.predict_p(P)
            err = (p - y) * sw
            gw = P.T @ err / max(len(y), 1)
            gb = float(err.mean())
            if method == "fedprox":
                gw += mu * (self.w - w0)
                gb += mu * (self.b - b0)
            elif method == "scaffold":
                gw += -self.ci + self.c
                gb += -self.ci_b + self.c_b
            gw = np.clip(finite_array(gw), -CONFIG["gradient_clip"], CONFIG["gradient_clip"])
            gb = float(np.clip(gb, -CONFIG["gradient_clip"], CONFIG["gradient_clip"]))
            self.w = np.clip(self.w - self.lr * gw, -CONFIG["parameter_clip"], CONFIG["parameter_clip"])
            self.b = float(np.clip(self.b - self.lr * gb, -CONFIG["parameter_clip"], CONFIG["parameter_clip"]))

        if method == "scaffold":
            k = max(int(epochs), 1)
            self.ci = self.ci - self.c + (w0 - self.w) / (k * self.lr + 1e-12)
            self.ci_b = self.ci_b - self.c_b + (b0 - self.b) / (k * self.lr + 1e-12)
            self.ci = finite_array(self.ci)
            self.ci_b = float(np.nan_to_num(self.ci_b))

        out = self.state(include_client=True)
        out["ci_delta"] = finite_array(self.ci - ci_old)
        out["ci_b_delta"] = float(self.ci_b - ci_b_old)
        return out

