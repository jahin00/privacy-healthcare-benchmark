def detect_text_separator(line):
    if "," in line:
        return ","
    if ";" in line:
        return ";"
    if "\t" in line:
        return "\t"
    return r"\s+"
def first_nonempty_lines(path, n=3):
    lines = []
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.strip():
                lines.append(line.rstrip("\n\r"))
            if len(lines) >= n:
                break
    return lines
def looks_like_header_line(line):
    parts = re.split(detect_text_separator(line), line.strip())
    normalized = {normalize_feature_name(p) for p in parts}
    recognized = len(normalized & HEADER_HINTS)
    if recognized >= 2:
        return True
    if any(x in normalized for x in {"target","label","class","outcome","diagnosis","condition"}):
        return True
    return False
def read_dataset_file(path):
    suffix = Path(path).suffix.lower()
    lines = first_nonempty_lines(path)
    if not lines:
        raise ValueError(f"Dataset file is empty: {path}")
    first_line = lines[0]
    sep = detect_text_separator(first_line)
    header_present = looks_like_header_line(first_line)

    if header_present:
        if sep == r"\s+":
            df = pd.read_csv(path, sep=sep, engine="python", header=0,
                             na_values=["?", "NA", "N/A", ""])
        else:
            df = pd.read_csv(path, sep=sep, header=0,
                             na_values=["?", "NA", "N/A", ""])
        return df, {"format":"headered","separator":sep,"header_present":True,"suffix":suffix}

    # headerless
    if sep == r"\s+":
        raw = pd.read_csv(path, sep=sep, engine="python", header=None,
                          na_values=["?", "NA", "N/A", ""])
    else:
        raw = pd.read_csv(path, sep=sep, header=None,
                          na_values=["?", "NA", "N/A", ""])
    ncols = raw.shape[1]
    if ncols == len(UCI_13_COLUMN_SCHEMA):
        raw.columns = UCI_13_COLUMN_SCHEMA
        return raw, {"format":"headerless_uci_13","separator":sep,
                     "header_present":False,"schema":UCI_13_COLUMN_SCHEMA,"suffix":suffix}
    if ncols == len(UCI_14_COLUMN_SCHEMA):
        raw.columns = UCI_14_COLUMN_SCHEMA
        return raw, {"format":"headerless_uci_14","separator":sep,
                     "header_present":False,"schema":UCI_14_COLUMN_SCHEMA,"suffix":suffix}
    # generic
    raw.columns = [f"column_{i+1}" for i in range(ncols)]
    return raw, {"format":"headerless_generic","separator":sep,
                 "header_present":False,"ncols":ncols,"suffix":suffix}

