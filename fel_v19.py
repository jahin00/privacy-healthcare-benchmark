def fit_local_scaler(X_train, global_features):
    median = {}
    mean = {}
    std = {}
    for feature in global_features:
        if feature not in X_train.columns:
            median[feature] = 0.0
            mean[feature] = 0.0
            std[feature] = 1.0
            continue
        col = pd.to_numeric(X_train[feature], errors="coerce").replace([np.inf, -np.inf], np.nan)
        valid = col.dropna()
        if len(valid) == 0:
            med = 0.0; mu = 0.0; sd = 1.0
        else:
            med = float(valid.median())
            filled = col.fillna(med)
            mu = float(filled.mean())
            sd = float(filled.std(ddof=0))
            sd = max(sd, 1e-8)
        median[feature] = med
        mean[feature] = mu
        std[feature] = sd
    return {"type": "client_local_train_fitted", "median": median, "mean": mean, "std": std}
def transform_local(X, global_features, scaler):
    values = np.zeros((len(X), len(global_features)), dtype=float)
    mask = np.zeros_like(values)
    positions = {f: i for i, f in enumerate(global_features)}
    for feature in global_features:
        j = positions[feature]
        if feature not in X.columns:
            continue
        raw = pd.to_numeric(X[feature], errors="coerce").replace([np.inf, -np.inf], np.nan)
        med = float(scaler["median"].get(feature, 0.0))
        mu = float(scaler["mean"].get(feature, 0.0))
        sd = max(float(scaler["std"].get(feature, 1.0)), 1e-8)
        raw = raw.fillna(med)
        values[:, j] = (raw.values.astype(float) - mu) / sd
        mask[:, j] = 1.0
    values = finite_array(values)
    mask = finite_array(mask)
    return values, mask

def class_weights(y, cap=2.5):
    y = np.asarray(y, dtype=int)
    n0 = max(int(np.sum(y == 0)), 1)
    n1 = max(int(np.sum(y == 1)), 1)
    total = n0 + n1
    return {0: min(total/(2.0*n0), cap), 1: min(total/(2.0*n1), cap)}

