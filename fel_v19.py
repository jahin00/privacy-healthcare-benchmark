def state_relative_change(previous, current):
    blocks = {
        "linear": ["w", "b"],
        "dnn": ["W1", "b1", "W2", "b2", "W3", "b3"],
        "meta": ["w", "b"],
    }
    diff_sq = 0.0
    prev_sq = 0.0
    for block, keys in blocks.items():
        for key in keys:
            a = finite_array(previous[block][key]).ravel()
            b = finite_array(current[block][key]).ravel()
            diff_sq += float(np.sum((b - a) ** 2))
            prev_sq += float(np.sum(a ** 2))
    return float(math.sqrt(diff_sq) / (math.sqrt(prev_sq) + 1e-12))

