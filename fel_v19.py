        self.X_test_raw = X_test
        self.y_train = np.asarray(y_train, dtype=int)
        self.y_val = np.asarray(y_val, dtype=int)
        self.y_test = np.asarray(y_test, dtype=int)

        self.preprocessor = fit_local_scaler(self.X_train_raw, self.global_features)

