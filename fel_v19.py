def metric_dict(y, p, threshold=0.5):
    y = np.asarray(y, dtype=int)
    p = finite_array(p)
    pred = (p >= threshold).astype(int)
    return {
        "accuracy": float(accuracy_score(y, pred)),
        "balanced_accuracy": float(balanced_accuracy_score(y, pred)),
        "f1": float(f1_score(y, pred, zero_division=0)),
        "auc": float(roc_auc_score(y, p)) if len(np.unique(y)) == 2 else 0.5,
        "confusion_matrix": confusion_matrix(y, pred).tolist(),
    }

def score_metric(metrics):
    weights = CONFIG["fel_score_weights"]
    return float(sum(weights[k] * metrics[k] for k in weights))

def threshold_search(y, p):
    candidates = []
    for threshold in CONFIG["threshold_grid"]:
        metrics = metric_dict(y, p, threshold)
        pred = (np.asarray(p) >= threshold).astype(int)
        both_classes = (len(np.unique(pred)) == 2)
        s = score_metric(metrics)
        candidates.append((s, threshold, metrics, both_classes))
    valid = [c for c in candidates if c[3]]
    if valid:
        return max(valid, key=lambda x: x[0])
    return max(candidates, key=lambda x: x[0])

def validate_stack_probability(p_stack):
    p = finite_array(p_stack)
    return {
        "min": float(np.min(p)),
        "mean": float(np.mean(p)),
        "max": float(np.max(p)),
        "std": float(np.std(p)),
        "saturated_high_fraction": float(np.mean(p >= 0.99)),
        "saturated_low_fraction": float(np.mean(p <= 0.01)),
    }

def choose_blend(y, p_stack, p_base):
    candidates = []
    for mix in [0.0, 0.25, 0.50, 0.75, 1.0]:
        p = mix * p_stack + (1.0 - mix) * p_base
        stats = validate_stack_probability(p)
        stack_collapsed = (np.std(p_stack) < 0.01 or
                           stats["saturated_high_fraction"] > 0.95 or
                           stats["saturated_low_fraction"] > 0.95)
        if stack_collapsed and mix > 0:
            continue
        ts = threshold_search(y, p)
        candidates.append((ts[0], mix, ts[1], ts[2], p, stats))
    if not candidates:
        ts = threshold_search(y, p_base)
        return (ts[0], 0.0, ts[1], ts[2], p_base, validate_stack_probability(p_stack))
    best = max(candidates, key=lambda z: z[0])
    return best

