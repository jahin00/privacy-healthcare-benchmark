def infer_target_column(df):
    normalized = {normalize_feature_name(c): c for c in df.columns}
    for name in TARGET_ALIASES:
        if name in normalized:
            return normalized[name]
    return None
def normalize_target(y_raw, target_col):
    nums = pd.to_numeric(y_raw, errors="coerce")
    name = normalize_feature_name(target_col)
    if nums.notna().all():
        values = np.sort(pd.unique(nums.astype(float)))
        if len(values) == 2:
            positive = values[-1]
            return ((nums.astype(float).values == positive).astype(int),
                    f"binary_numeric: {values[0]}->0, {positive}->1")
        if name in {"num", "diagnosis", "diagnostic", "condition",
                    "heartdisease", "heart_disease"}:
            integer_values = {int(v) for v in values if float(v).is_integer()}
            if 0 in integer_values and integer_values.issubset({0,1,2,3,4}):
                return ((nums.astype(float).values > 0).astype(int),
                        "UCI ordinal: 0->no disease, >1->disease")
        raise ValueError(f"Target '{target_col}' has unsupported numeric levels: {values.tolist()}")
    values = y_raw.astype(str).str.strip().str.lower()
    unique = list(pd.unique(values))
    if set(unique).issubset({"0", "1"}):
        return (values.astype(int).values, "string_binary: 0/1")
    positive_words = {"disease","diseased","yes","y","true","positive","present","abnormal","patient"}
    negative_words = {"no","n","false","negative","absent","healthy","normal","control","no_disease","no disease"}
    mapping = None
    if set(unique).issubset(positive_words | negative_words):
        pos = [v for v in unique if v in positive_words]
        neg = [v for v in unique if v in negative_words]
        if len(pos) == 1 and len(neg) == 1:
            mapping = {neg[0]:0, pos[0]:1}
    if mapping is None:
        if len(unique) != 2:
            raise ValueError(f"Target '{target_col}' is not binary: {unique}")
        mapping = {value: idx for idx, value in enumerate(sorted(unique))}
    return (values.map(mapping).astype(int).values, f"categorical_binary: {mapping}")

