def choose_fl_method(native):
    names = list(native.keys())
    feature_sets = [set(native[n][0].columns) for n in names]
    rates = [float(np.mean(native[n][1])) for n in names]
    sample_sizes = [len(native[n][1]) for n in names]
    jaccards = []
    for i in range(len(feature_sets)):
        for j in range(i + 1, len(feature_sets)):
            union = feature_sets[i] | feature_sets[j]
            if union:
                jaccards.append(len(feature_sets[i] & feature_sets[j]) / len(union))
    mean_jaccard = float(np.mean(jaccards)) if jaccards else 1.0
    rate_spread = max(rates) - min(rates)
    size_ratio = max(sample_sizes) / max(min(sample_sizes), 1)
    heterogeneity = (0.45 * (1.0 - mean_jaccard) +
                     0.40 * min(rate_spread / 0.35, 1.0) +
                     0.15 * min((size_ratio - 1.0) / 3.0, 1.0))
    if heterogeneity < 0.25:
        method = "fedavg"
    elif heterogeneity < 0.55:
        method = "fedprox"
    else:
        method = "scaffold"
    print("\n[FL STRATEGY]")
    print(f"  Mean feature Jaccard : {mean_jaccard:.3f}")
    print(f"  Label-rate spread    : {rate_spread:.3f}")
    print(f"  Sample-size ratio    : {size_ratio:.2f}")
    print(f"  Heterogeneity score  : {heterogeneity:.3f}")
    print(f"  Selected strategy    : {method.upper()}")
    return method

