def canonical_column_map(columns):
    normalized = {normalize_feature_name(c): c for c in columns}
    reverse_alias = {}
    for canonical, aliases in FEATURE_ALIASES.items():
        for alias in aliases:
            reverse_alias[normalize_feature_name(alias)] = canonical
    result = {}
    for normalized_name, original in normalized.items():
        if normalized_name in reverse_alias:
            canonical = reverse_alias[normalized_name]
            if canonical not in result:
                result[canonical] = original
    return result
def looks_like_corrupt_feature_name(name):
    s = normalize_feature_name(name)
    if s in CANONICAL_FEATURES:
        return False
    if s == "?":
        return True
    try:
        float(s)
        return True
    except Exception:
        pass
    if "?" in s:
        return True
    parts = s.split("_")
    if parts and all(part.isdigit() for part in parts if part != ""):
        return True
    return False
def load_client_csv(path, client_name):
    if not os.path.isfile(path):
        raise FileNotFoundError(f"{client_name}: dataset not found:\n{path}")
    df, file_info = read_dataset_file(path)
    if df.empty:
        raise ValueError(f"{client_name}: dataset contains no rows.")
    original_columns = list(df.columns)
    print(f"\n{client_name} file parser:")
    print(f"  path        : {path}")
    print(f"  format      : {file_info.get('format')}")
    print(f"  separator   : {file_info.get('separator')}")
    print(f"  header      : {file_info.get('header_present')}")
    print(f"  raw columns : {len(original_columns)}")

    if file_info.get("header_present"):
        corrupt_headers = [c for c in original_columns if looks_like_corrupt_feature_name(c)]
        if corrupt_headers:
            raise ValueError(
                f"\n{client_name}: INVALID CSV HEADER DETECTED.\n"
                f"These column names look like patient values:\n{corrupt_headers}\n\n"
                f"Check that the first row of the dataset contains column names."
            )
    target_col = infer_target_column(df)
    if target_col is None:
        raise ValueError(f"\n{client_name}: Could not identify target column.\nColumns found:\n{original_columns}")
    y, target_mapping = normalize_target(df[target_col], target_col)
    feature_df = df.drop(columns=[target_col]).copy()
    drop_columns = []
    for col in feature_df.columns:
        norm = normalize_feature_name(col)
        if norm in IGNORED_COLUMNS or norm.startswith("unnamed") or norm == "extra":
            drop_columns.append(col)
    if drop_columns:
        feature_df = feature_df.drop(columns=drop_columns)
    semantic_map = canonical_column_map(feature_df.columns)
    if not semantic_map:
        raise ValueError(f"\n{client_name}: No validated heart-disease clinical features were recognized.\nColumns found: {list(feature_df.columns)}")
    X = pd.DataFrame(index=feature_df.index)
    for canonical, original in semantic_map.items():
        X[canonical] = pd.to_numeric(feature_df[original], errors="coerce")
    unknown_columns = [c for c in feature_df.columns if c not in semantic_map.values()]
    print(f"  recognized : {len(X.columns)} clinical features")
    print(f"  target     : {target_col!r}")
    print(f"  target map : {target_mapping}")
    print(f"  pos rate   : {np.mean(y):.4f}")
    if unknown_columns:
        print("  ignored columns:", unknown_columns)
    return X, np.asarray(y, dtype=int), target_col, target_mapping

